using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace KandaEu.Volejbal.OpenApiGenerator;

/// <summary>
/// Vygeneruje OpenAPI 3.0 dokument z Refit rozhraní (I*Api) v referencovaných assembly a uloží ho
/// jako konstantu <c>GeneratedOpenApiDocument.Json</c> v kompilovaném projektu.
/// </summary>
/// <remarks>
/// Běží v projektu, který kontrakty referencuje (Api), ne v Contracts: dokument tak nekončí ve WebAssembly
/// klientovi, který Contracts také referencuje, a generátor může do odpovědí doplnit chybový model z Api.
/// Výstup je čistý text vzniklý při kompilaci - za běhu se nic nereflektuje.
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class OpenApiIncrementalGenerator : IIncrementalGenerator
{
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		IncrementalValueProvider<GeneratorOptions> options = context.AnalyzerConfigOptionsProvider
			.Select(static (provider, _) => GeneratorOptions.FromGlobalOptions(provider.GlobalOptions));

		// XML dokumentace referencovaných projektů - AdditionalFiles označené v OpenApiGenerator.props.
		IncrementalValueProvider<ImmutableArray<string>> documentationFiles = context.AdditionalTextsProvider
			.Combine(context.AnalyzerConfigOptionsProvider)
			.Where(static pair => pair.Right.GetOptions(pair.Left).TryGetValue("build_metadata.AdditionalFiles.OpenApiDocumentation", out string flag) && String.Equals(flag, "true", StringComparison.OrdinalIgnoreCase))
			.Select(static (pair, cancellationToken) => pair.Left.GetText(cancellationToken)?.ToString() ?? String.Empty)
			.Collect();

		IncrementalValueProvider<string> json = context.CompilationProvider
			.Combine(options)
			.Combine(documentationFiles)
			.Select(static (pair, cancellationToken) => OpenApiDocumentBuilder.Build(pair.Left.Left, pair.Left.Right, pair.Right, cancellationToken));

		context.RegisterSourceOutput(json.Combine(options), static (productionContext, pair) =>
		{
			if (pair.Left == null)
			{
				// Žádné Refit rozhraní v dosahu - projekt generátor používá omylem, nic negenerujeme.
				return;
			}

			productionContext.AddSource("GeneratedOpenApiDocument.g.cs", SourceText.From(BuildSource(pair.Left, pair.Right.RootNamespace), Encoding.UTF8));
		});
	}

	private static string BuildSource(string json, string rootNamespace)
	{
		StringBuilder builder = new StringBuilder();
		builder.AppendLine("// <auto-generated/>");
		builder.AppendLine("// Vygenerováno zdrojovým generátorem KandaEu.Volejbal.OpenApiGenerator z Refit rozhraní v Contracts.");
		builder.AppendLine();

		bool hasNamespace = !String.IsNullOrWhiteSpace(rootNamespace);
		if (hasNamespace)
		{
			builder.Append("namespace ").Append(rootNamespace).AppendLine(".OpenApi;");
			builder.AppendLine();
		}

		builder.AppendLine("/// <summary>");
		builder.AppendLine("/// OpenAPI dokument HTTP API, sestavený při kompilaci z Refit kontraktů (I*Api).");
		builder.AppendLine("/// </summary>");
		builder.AppendLine("public static class GeneratedOpenApiDocument");
		builder.AppendLine("{");
		builder.AppendLine("\t/// <summary>Dokument ve formátu JSON (OpenAPI 3.0.3).</summary>");
		builder.Append("\tpublic const string Json = ").Append(SymbolDisplay.FormatLiteral(json, quote: true)).AppendLine(";");
		builder.AppendLine("}");

		return builder.ToString();
	}
}
